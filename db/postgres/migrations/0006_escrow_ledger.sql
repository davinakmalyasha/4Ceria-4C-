-- =============================================================================
-- 0006 — The escrow ledger.
--
-- WHY THIS FILE EXISTS
-- --------------------
-- `project_budget_transactions` is the audit record of every rupiah that has
-- moved against a project's escrow. It is the reason a figure can be
-- explained after the fact, and it is the ONLY place the escrow's truth
-- lives.
--
-- THREE THINGS CHANGE HERE, and each one closes a defect that cost money.
--
-- 1. THE REFERENCE BECOMES A REGISTRY KEY (ADR-0013)
--    `reference_model` was a VARCHAR holding an Eloquent class name. The
--    live database held the same Rp 5 500 000 payment written twice, under
--    two spellings of the same model:
--
--        id 5619  'ProjectAddendum'
--        id 5918  'App\Models\ProjectAddendum'
--
--    The unique index that makes the ledger idempotent is keyed on the
--    reference, so two spellings do not collide, the index cannot see them
--    as the same movement, and the escrow is understated by exactly
--    Rp 5 500 000. A `smallint` cannot be spelled two ways.
--
-- 2. THE INVARIANT MOVES INTO THE DATABASE (ADR-0020)
--    `AGENTS.md` trap 12 says "never write a ledger row directly" — and it
--    was a CONVENTION. It is now a PRIVILEGE: the application role cannot
--    INSERT, UPDATE or DELETE a ledger row at all. It calls
--    `escrow.record_movement()`, which performs the whole movement
--    atomically and refuses to move money that is not there.
--
-- 3. THE CEILING MOVES ONCE, AND ONLY FOR THE TWO STRUCTURAL TYPES
--    `deposit` raises the ceiling and `adjustment_down` lowers it. The four
--    disbursement types SPEND the ceiling without moving it. The old test was
--    `type != 'payment'`, which sent `platform_fee` and `retention_release`
--    down the ceiling-decrement branch as well and subtracted the same
--    rupiah twice. The test is a MEMBERSHIP test now, and it is in the
--    function, so it cannot be mis-written per endpoint (MONEY.md §2).
--
-- THE FOUR COLUMNS THAT ARE DROPPED
-- ---------------------------------
-- `category`, `type`, `status` and `description` existed on the legacy table
-- and were never written by anything: they are not in the model's $fillable,
-- and no code path sets them. They are dropped rather than carried forward as
-- four columns of noise that a future reader would assume mean something.
--
-- `actor_user_id` deliberately has NO foreign key. The ledger is an
-- immutable historical record: deleting a user must not erase the fact that
-- they moved the money (the legacy schema made the same choice).

-- -----------------------------------------------------------------------------
-- The ledger vocabulary. The six values are the legacy ENUM's, in the legacy
-- order (MONEY.md §2).
-- -----------------------------------------------------------------------------

CREATE TYPE transaction_type AS ENUM (
    'deposit', 'adjustment_down', 'payment', 'refund',
    'platform_fee', 'retention_release'
);

-- -----------------------------------------------------------------------------
-- project_budget_transactions  (legacy table: project_budget_transactions)
-- -----------------------------------------------------------------------------
CREATE TABLE project_budget_transactions (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id             bigint NOT NULL,
    transaction_type       transaction_type NOT NULL,
    amount                 numeric(24,2) NOT NULL,
    title                  text NOT NULL,

    -- WHAT THIS ROW IS ABOUT, and the dedupe key. `reference_type_id` points
    -- at the registry (0002); `reference_id` is the id in the registry's
    -- `target_table`.
    reference_type_id      smallint,
    reference_id           bigint,

    -- WHAT THIS ROW REVERSES, for a refund. Kept separate from `reference_*`
    -- on purpose: a refund's reference is the DISPUTE and its reversal is
    -- the PAYMENT, so one payment can be refunded across several disputes
    -- and one dispute gets at most one refund (MONEY.md §4.4).
    reverses_type_id       smallint,
    reverses_id            bigint,

    transaction_date       timestamptz NOT NULL DEFAULT now(),

    -- WHO moved the money. NULL means no human actor: a scheduled
    -- settlement, a reconciliation repair, a system-generated opening
    -- balance. That is a real answer, not missing data.
    actor_user_id          bigint,
    actor_role             text,

    -- Set by the migration that voided a duplicate movement. A row is voided,
    -- never un-voided.
    voided_at              timestamptz,
    voided_duplicate_of_id bigint,
    voided_original_amount numeric(24,2),

    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT project_budget_transactions_project_id_fkey FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT project_budget_transactions_reference_type_id_fkey FOREIGN KEY (reference_type_id) REFERENCES ledger_reference_types (id),
    CONSTRAINT project_budget_transactions_reverses_type_id_fkey  FOREIGN KEY (reverses_type_id)  REFERENCES ledger_reference_types (id),

    -- A movement that is not structural MUST name what it is about.
    --
    -- A VOIDED row is exempt: voiding a duplicate is recorded by NULLing the
    -- reference it was wrongly given, so requiring one would make the voided
    -- row unrepresentable and the audit trail incomplete (see pbt_amount_sign).
    CONSTRAINT pbt_reference_required CHECK (
        voided_at IS NOT NULL
        OR transaction_type IN ('deposit','adjustment_down')
        OR reference_id IS NOT NULL
    ),

    -- ...and a structural movement must name NOTHING. A deposit is not about
    -- a bid, and letting it carry a reference would put it back into the
    -- dedupe key.
    CONSTRAINT pbt_structural_no_reference CHECK (
        voided_at IS NOT NULL
        OR transaction_type NOT IN ('deposit','adjustment_down')
        OR (reference_type_id IS NULL AND reference_id IS NULL)
    ),

    -- A refund is the ONLY negative movement. Everything else is positive.
    --
    -- A VOIDED row is exempt, and the live data is why: the duplicate the
    -- project voided in place (id 5619) was zeroed when it was voided, so a
    -- strict sign rule makes the historical record UNREPRESENTABLE — the ETL
    -- refuses to load it, or silently drops it, and either way the audit trail
    -- loses the row that explains Rp 5 500 000.
    --
    -- A voided row is not a movement: it is the marker that a movement was
    -- withdrawn. The write path cannot create one (`escrow.record_movement`
    -- refuses a zero amount), so this exemption cannot be reached by an INSERT.
    CONSTRAINT pbt_amount_sign CHECK (
        voided_at IS NOT NULL
     OR (transaction_type = 'refund' AND amount < 0)
     OR (transaction_type <> 'refund' AND amount > 0)
    ),

    -- A refund reverses something.
    CONSTRAINT pbt_refund_reverses CHECK (
        voided_at IS NOT NULL
        OR transaction_type <> 'refund'
        OR (reverses_type_id IS NOT NULL AND reverses_id IS NOT NULL)
    )
);

-- THE DEDUPE KEY.
--
-- `NULLS NOT DISTINCT` is what makes a row whose reference key is only
-- PARTIALLY populated still dedupe against another such row. Under the
-- default NULLS-DISTINCT semantics two rows with a NULL in the key are
-- never equal, so the guard would silently stop working for exactly the rows
-- it is hardest to reason about.
--
-- The index is PARTIAL (`WHERE reference_id IS NOT NULL`) on purpose, and
-- this is the one place where the obvious alternative is a BUG. A table-level
-- `UNIQUE NULLS NOT DISTINCT (project_id, reference_type_id, reference_id,
-- transaction_type)` would treat every structural row — every deposit and
-- every adjustment_down, which carry NO reference — as the SAME key, because
-- all three reference columns are NULL. A project would then be able to
-- receive exactly ONE deposit, ever. A deposit must be repeatable (MONEY.md
-- section 4.4), so the structural rows are excluded from the key and only
-- movements that name WHAT they are about are deduplicated.
--
-- It is an INDEX rather than a table CONSTRAINT for the same reason: a
-- partial unique constraint cannot be expressed as a table constraint, and
-- the partiality is the whole point.
CREATE UNIQUE INDEX budget_tx_reference_unique
    ON project_budget_transactions (project_id, reference_type_id, reference_id, transaction_type)
    NULLS NOT DISTINCT
    WHERE reference_id IS NOT NULL;

COMMENT ON TABLE project_budget_transactions IS
    'The escrow ledger. One row per movement of money against a project''s '
    'escrow. Written ONLY through escrow.record_movement(): the application '
    'role has no INSERT, UPDATE or DELETE privilege on this table (ADR-0020).';

COMMENT ON COLUMN project_budget_transactions.reference_type_id IS
    'The registry key naming what this row is about (ADR-0013). It replaces '
    'the polymorphic reference_model VARCHAR, whose two spellings of the same '
    'model understated a live escrow by Rp 5 500 000.';

COMMENT ON COLUMN project_budget_transactions.reverses_type_id IS
    'The registry key naming what this row REVERSES. For a refund that is the '
    'payment being returned; the refund''s own reference is the dispute.';

COMMENT ON COLUMN project_budget_transactions.actor_user_id IS
    'The human who caused this movement, if a human did. NULL is a system '
    'movement. Deliberately NOT a foreign key: the ledger is an immutable '
    'historical record, and deleting a user must not erase the fact that '
    'they moved the money.';

CREATE INDEX budget_tx_project_type_idx ON project_budget_transactions (project_id, transaction_type);
CREATE INDEX budget_tx_project_actor_idx ON project_budget_transactions (project_id, actor_user_id);
CREATE INDEX budget_tx_reverses_idx ON project_budget_transactions (project_id, reverses_type_id, reverses_id);
CREATE INDEX budget_tx_reference_id_idx ON project_budget_transactions (reference_type_id, reference_id);
CREATE INDEX budget_tx_transaction_date_idx ON project_budget_transactions (transaction_date DESC);

-- =============================================================================
-- THE WRITE PATH
--
-- There is exactly ONE writer. It is a SECURITY DEFINER function, so that
-- the application role can execute it without holding INSERT on the table,
-- and so that the affordability check, the dedupe guard and the ceiling
-- movement happen inside ONE transaction, in ONE order, with no way to
-- interleave another payment between them.
--
-- THE ORDER MATTERS. The insert comes BEFORE the ceiling move. In the PHP
-- original the ceiling was decremented first and the unique violation was
-- caught INSIDE the transaction, so a duplicate could commit a ceiling
-- change with no ledger row (MONEY.md §5).
--
-- THE CALLER MUST INSPECT THE RESULT. `written = false` means the movement
-- was already recorded: an IDEMPOTENT SUCCESS with no ceiling move and no
-- platform fee. A discarded result is how a bid ends up `paid` with no
-- ledger row (AGENTS.md trap 12).
-- =============================================================================

CREATE OR REPLACE FUNCTION escrow.record_movement(
    p_project_id        bigint,
    p_type              transaction_type,
    p_amount            numeric(24,2),
    p_title             text,
    p_reference_type_id smallint DEFAULT NULL,
    p_reference_id      bigint   DEFAULT NULL,
    p_reverses_type_id  smallint DEFAULT NULL,
    p_reverses_id       bigint   DEFAULT NULL,
    p_actor_user_id     bigint   DEFAULT NULL,
    p_actor_role        text     DEFAULT NULL
) RETURNS TABLE (
    ledger_id bigint,
    written   boolean,
    ceiling   numeric(24,2),
    available numeric(24,2)
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, escrow
AS $$
DECLARE
    v_ceiling        numeric(24,2);
    v_outflow        numeric(24,2);
    v_outflow_after  numeric(24,2);
    v_ledger_id      bigint;
    v_written        boolean;

    -- The three type-lists of MONEY.md section 2. They are declared HERE,
    -- once, because the bug this schema exists to prevent was the same list
    -- being written three different ways in three different files.
    --
    --   DISBURSEMENT_TYPES         what LEFT the escrow
    --   CEILING_NEUTRAL_TYPES       what SPENT the escrow without moving the
    --                               ceiling (the same four: they spend, but
    --                               only deposit and adjustment_down move
    --                               the ceiling)
    --   PROFESSIONAL_EARNINGS_TYPES what REACHED a professional — platform_fee
    --                               is the platform's revenue and is excluded
    c_disbursement_types constant transaction_type[] := ARRAY[
        'payment', 'refund', 'platform_fee', 'retention_release'
    ]::transaction_type[];
    c_ceiling_neutral_types constant transaction_type[] := ARRAY[
        'payment', 'refund', 'platform_fee', 'retention_release'
    ]::transaction_type[];
BEGIN
    IF p_type IS NULL THEN
        RAISE EXCEPTION 'a ledger movement needs a transaction type'
            USING ERRCODE = '22004';
    END IF;
    IF p_amount IS NULL OR p_amount = 0 THEN
        RAISE EXCEPTION 'a ledger movement needs a non-zero amount'
            USING ERRCODE = '22004';
    END IF;

    -- 1. Lock the ceiling row. This serialises every concurrent payment on
    --    the project, and everything below is computed INSIDE the lock.
    SELECT p.budget INTO v_ceiling
      FROM projects p
     WHERE p.id = p_project_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'project % not found', p_project_id
            USING ERRCODE = 'P0002';
    END IF;

    -- 2. The outflow. Computed inside the lock, from the ledger and never
    --    from a cached or denormalised figure. Refund rows are NEGATIVE and
    --    are part of this same sum: excluding them would leave refunded money
    --    permanently consumed.
    SELECT COALESCE(SUM(t.amount), 0) INTO v_outflow
      FROM project_budget_transactions t
     WHERE t.project_id = p_project_id
       AND t.transaction_type = ANY (c_disbursement_types);

    -- 3. Affordability. A deposit is NEVER limited by the current balance
    --    (MONEY.md I6): a deposit RAISES the ceiling, so there is nothing to
    --    be short of. Everything else must fit inside what is left.
    IF p_type <> 'deposit' AND (v_ceiling - v_outflow) < p_amount THEN
        RAISE EXCEPTION 'insufficient escrow: need %, available %',
              p_amount, (v_ceiling - v_outflow)
            USING ERRCODE = 'P0001', DETAIL = 'insufficient_funds';
    END IF;

    -- 4. The dedupe guard, atomic. Zero rows returned means the movement was
    --    already recorded: an idempotent success with NO ceiling move and
    --    NO platform fee.
    INSERT INTO project_budget_transactions (
        project_id, transaction_type, amount, title,
        reference_type_id, reference_id, reverses_type_id, reverses_id,
        transaction_date, actor_user_id, actor_role
    ) VALUES (
        p_project_id, p_type, p_amount, p_title,
        p_reference_type_id, p_reference_id, p_reverses_type_id, p_reverses_id,
        now(), p_actor_user_id, p_actor_role
    )
    ON CONFLICT (project_id, reference_type_id, reference_id, transaction_type)
        WHERE reference_id IS NOT NULL
    DO NOTHING
    RETURNING id INTO v_ledger_id;

    v_written := (v_ledger_id IS NOT NULL);

    IF NOT v_written THEN
        RETURN QUERY SELECT NULL::bigint, false, v_ceiling, (v_ceiling - v_outflow);
        RETURN;
    END IF;

    -- 5. The ceiling moves ONLY for the two structural types. A MEMBERSHIP
    --    test, never `type != 'payment'` — that test double-subtracted
    --    platform_fee and retention_release (MONEY.md section 2).
    IF NOT (p_type = ANY (c_ceiling_neutral_types)) THEN
        UPDATE projects p
           SET budget = p.budget + CASE WHEN p_type = 'adjustment_down'
                                       THEN -p_amount ELSE p_amount END,
               updated_at = now()
         WHERE p.id = p_project_id
        RETURNING p.budget INTO v_ceiling;

        IF v_ceiling < 0 THEN
            RAISE EXCEPTION 'the escrow ceiling cannot go negative (project %)',
                  p_project_id
                USING ERRCODE = 'P0001', DETAIL = 'negative_ceiling';
        END IF;
    END IF;

    -- 6. The available balance AFTER the movement. The ADR-0020 sketch
    --    returned the figure computed BEFORE the insert, which is the
    --    available balance the caller had before it moved the money; a
    --    caller that trusted it would have believed the escrow was unchanged.
    SELECT COALESCE(SUM(t.amount), 0) INTO v_outflow_after
      FROM project_budget_transactions t
     WHERE t.project_id = p_project_id
       AND t.transaction_type = ANY (c_disbursement_types);

    RETURN QUERY SELECT v_ledger_id, true, v_ceiling, (v_ceiling - v_outflow_after);
END;
$$;

COMMENT ON FUNCTION escrow.record_movement(bigint, transaction_type, numeric, text, smallint, bigint, smallint, bigint, bigint, text) IS
    'The ONLY writer of the escrow ledger. Performs the affordability check, '
    'the dedupe guard and the ceiling movement inside one transaction and one '
    'row lock. `written = false` means the movement was already recorded: an '
    'idempotent success with no ceiling move and no platform fee. The caller '
    'MUST inspect the result.';

-- =============================================================================
-- THE READ PATH
--
-- "How much is left" is answered by these functions and by nothing else.
-- The client must never compute it, and the server must never read
-- `projects.budget` outside these functions (MONEY.md §13).
-- =============================================================================

CREATE OR REPLACE FUNCTION escrow.available(p_project_id bigint)
RETURNS numeric(24,2)
LANGUAGE sql
STABLE
SET search_path = public, escrow
AS $$
    SELECT COALESCE(p.budget, 0) - COALESCE((
        SELECT SUM(t.amount)
          FROM project_budget_transactions t
         WHERE t.project_id = p.id
           AND t.transaction_type = ANY (ARRAY[
                   'payment','refund','platform_fee','retention_release'
               ]::transaction_type[])
    ), 0)
      FROM projects p
     WHERE p.id = p_project_id;
$$;

COMMENT ON FUNCTION escrow.available(bigint) IS
    'The escrow balance still available: the ceiling minus the disbursements. '
    'The ceiling is projects.budget, which only deposit and adjustment_down '
    'move; the outflow is the ledger''s. Never compute this in the client.';

CREATE OR REPLACE FUNCTION escrow.summary(p_project_id bigint)
RETURNS TABLE (
    ceiling     numeric(24,2),
    disbursed   numeric(24,2),
    available   numeric(24,2)
)
LANGUAGE sql
STABLE
SET search_path = public, escrow
AS $$
    SELECT
        COALESCE(p.budget, 0) AS ceiling,
        COALESCE((
            SELECT SUM(t.amount)
              FROM project_budget_transactions t
             WHERE t.project_id = p.id
               AND t.transaction_type = ANY (ARRAY[
                       'payment','refund','platform_fee','retention_release'
                   ]::transaction_type[])
        ), 0) AS disbursed,
        COALESCE(p.budget, 0) - COALESCE((
            SELECT SUM(t.amount)
              FROM project_budget_transactions t
             WHERE t.project_id = p.id
               AND t.transaction_type = ANY (ARRAY[
                       'payment','refund','platform_fee','retention_release'
                   ]::transaction_type[])
        ), 0) AS available
      FROM projects p
     WHERE p.id = p_project_id;
$$;

COMMENT ON FUNCTION escrow.summary(bigint) IS
    'The three figures a client is allowed to see about an escrow: the '
    'ceiling, what has been disbursed, and what is left.';

-- =============================================================================
-- THE PRIVILEGES — "never write a ledger row directly" becomes a PRIVILEGE
-- =============================================================================

-- Nothing may write the ledger directly. PUBLIC first, because a table
-- grants nothing by default but the role grants below are explicit.
REVOKE ALL ON project_budget_transactions FROM PUBLIC;
REVOKE INSERT, UPDATE, DELETE ON project_budget_transactions FROM app_rw;

-- Reading is allowed; writing is not.
GRANT SELECT ON project_budget_transactions TO app_rw;
GRANT SELECT ON project_budget_transactions TO app_ro;

-- The functions are the only way in and the only way to read a balance.
-- USAGE on the schema is what lets the application role resolve the
-- function name at all: without it, EXECUTE is not enough.
GRANT USAGE ON SCHEMA escrow TO app_rw, app_ro;

REVOKE EXECUTE ON FUNCTION escrow.record_movement(bigint, transaction_type, numeric, text, smallint, bigint, smallint, bigint, bigint, text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION escrow.available(bigint) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION escrow.summary(bigint) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION escrow.record_movement(bigint, transaction_type, numeric, text, smallint, bigint, smallint, bigint, bigint, text) TO app_rw;
GRANT EXECUTE ON FUNCTION escrow.available(bigint) TO app_rw, app_ro;
GRANT EXECUTE ON FUNCTION escrow.summary(bigint) TO app_rw, app_ro;

-- The function is SECURITY DEFINER, so it runs as its OWNER. The owner must
-- not be the application role: a SECURITY DEFINER function owned by the
-- application role would give that role everything the function can do,
-- which is the privilege this file exists to remove. In production the owner
-- is a dedicated role with no LOGIN.
COMMENT ON FUNCTION escrow.record_movement(bigint, transaction_type, numeric, text, smallint, bigint, smallint, bigint, bigint, text) IS
    'The ONLY writer of the escrow ledger. Performs the affordability check, '
    'the dedupe guard and the ceiling movement inside one transaction and one '
    'row lock. `written = false` means the movement was already recorded: an '
    'idempotent success with no ceiling move and no platform fee. The caller '
    'MUST inspect the result. SECURITY DEFINER: the function must be owned by '
    'a role that is NOT app_rw.';
