-- --------------------------------------------------------------------------
-- users  (legacy table: `users`)
-- The identity table. It stays in MySQL for the whole transition (ADR-0018),
-- but the baseline carries it because the port needs it eventually, and
-- because the Eloquent model reads it on every authenticated request.
--
-- THE COLUMNS THAT HAD TO BE THOUGHT ABOUT:
--
--   email        citext. Login is 'User::where(email, $request->email)'
--                (AuthController:38) and the STORED value is lowercased by
--                the registration path (AuthController:81) while the LOOKED-UP
--                value is the raw request. Under MySQL's case-insensitive
--                collation that mismatch was invisible. Under PostgreSQL's
--                default it would be a 404 on every differently-cased login.
--
--   username     citext. Human-typed, globally unique, and the public
--                professional directory keys on it.
--
--   unique_code  citext. A six-character code from an UPPERCASE alphabet,
--                used by the firm roster. The app already normalises the
--                query with strtoupper() (FirmMemberService:24), so citext is
--                belt-and-braces here rather than load-bearing - but it costs
--                nothing and it preserves MySQL's uniqueness semantics
--                exactly.
--
--   role_type    the native enum. It is a machine-written vocabulary, so it
--                is CASE-SENSITIVE on purpose: a typo must fail loudly
--                rather than silently match (AGENTS.md trap 8).
-- --------------------------------------------------------------------------
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name text NOT NULL,
    CONSTRAINT users_name_length CHECK (char_length(name) <= 255),
    email citext NOT NULL,
    CONSTRAINT users_email_length CHECK (char_length(email) <= 255),
    username citext,
    CONSTRAINT users_username_length CHECK (char_length(username) <= 255),
    unique_code citext,
    CONSTRAINT users_unique_code_length CHECK (char_length(unique_code) <= 6),
    email_verified_at timestamptz,
    password text NOT NULL,
    CONSTRAINT users_password_length CHECK (char_length(password) <= 255),
    pic text,
    CONSTRAINT users_pic_length CHECK (char_length(pic) <= 255),
    firm_name text,
    CONSTRAINT users_firm_name_length CHECK (char_length(firm_name) <= 255),
    firm_slogan text,
    CONSTRAINT users_firm_slogan_length CHECK (char_length(firm_slogan) <= 255),
    firm_banner_path text,
    CONSTRAINT users_firm_banner_path_length CHECK (char_length(firm_banner_path) <= 255),
    firm_description text,
    firm_is_hiring boolean NOT NULL DEFAULT false,
    firm_needed_roles jsonb,
    deskripsi text,
    bank_name text,
    CONSTRAINT users_bank_name_length CHECK (char_length(bank_name) <= 255),
    bank_account_number text,
    CONSTRAINT users_bank_account_number_length CHECK (char_length(bank_account_number) <= 255),
    bank_account_name text,
    CONSTRAINT users_bank_account_name_length CHECK (char_length(bank_account_name) <= 255),
    remember_token text,
    CONSTRAINT users_remember_token_length CHECK (char_length(remember_token) <= 100),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    role_type role_type DEFAULT 'user',
    is_suspended boolean NOT NULL DEFAULT false,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_unique_code_key UNIQUE (unique_code),
    CONSTRAINT users_username_key UNIQUE (username)
);

CREATE INDEX users_role_type_idx ON users (role_type);

