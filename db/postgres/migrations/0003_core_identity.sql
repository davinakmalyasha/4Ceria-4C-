-- --------------------------------------------------------------------------
-- notifications  (legacy table: `notifications`)
-- The in-app notification centre. 'data' is jsonb: it is a structured
-- payload that the SPA reads key by key, and jsonb gives it GIN-indexable
-- operators for free.
-- --------------------------------------------------------------------------
CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    type text NOT NULL,
    CONSTRAINT notifications_type_length CHECK (char_length(type) <= 255),
    title text NOT NULL,
    CONSTRAINT notifications_title_length CHECK (char_length(title) <= 255),
    body text NOT NULL,
    -- `json`, NOT `jsonb`.
    --
    -- The API ECHOES this document back inside the response, and PHP decodes
    -- and re-encodes it — preserving KEY ORDER. `jsonb` normalises the value
    -- into a binary form that SORTS keys, so a notification whose data is
    -- `{"b":1,"a":2}` would answer `{"a":2,"b":1}`. `json` keeps the text, the
    -- order and the numbers exactly as written.
    data json,
    read_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    CONSTRAINT notifications_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX notifications_user_created_idx ON notifications (user_id, created_at);
CREATE INDEX notifications_user_id_read_at_index ON notifications (user_id, read_at);
CREATE INDEX notifications_user_read_created_idx ON notifications (user_id, read_at, created_at);

