-- =============================================================================
-- 0003 — Core identity, profiles and the professional roster.
--
-- WHY THIS FILE EXISTS
-- --------------------
-- Everything in the application hangs off a person: a user, the professional
-- profile that describes what that user does, and the permissions that decide
-- what they may do. Those tables come first because every later file
-- references them.
--
-- THE ID SPACES — THE ONE CONVENTION
-- ----------------------------------
-- A user id is a user id. A profile id is a profile id. They are DIFFERENT
-- id spaces and the schema keeps them apart:
--
--   users.id                    the account
--   arsiteks.id, kontraktors.id, notaris_profiles.id,
--   interior_profiles.id, structural_engineers.id,
--   mep_engineers.id, project_managers.id    the professional profile
--
-- Every profile table carries a 'user_id' that points at the account, and
-- every 'projects.selected_*' column and every bid's profile column points at
-- the PROFILE, never at the user (ADR-0015). The legacy schema got this
-- wrong for exactly one role: 'projects.pm_id' held the PM's USER id while
-- the other six held profile ids. The 2026-10-21 migration fixed it, and
-- this baseline expresses the rule with foreign keys so it cannot drift
-- again.
--
-- THE COLLATATION DECISION (ADR-0008)
-- -----------------------------------
-- Six columns in this file are 'citext', and they are the six whose
-- case-insensitivity was LOAD-BEARING in MySQL:
--
--   users.email                  login and password reset
--   password_reset_tokens.email  the reset link
--   personal_access_tokens.token every Sanctum bearer-token lookup
--   users.username               the public professional directory
--   users.unique_code            the firm roster
--   (projects.share_token is in 0004)
--
-- Everything else here is case-SENSITIVE on purpose. An enum value, a
-- permission name, a channel code, a slug: these are machine-written from a
-- fixed vocabulary, and a case-insensitive comparison there would HIDE a
-- typo rather than catch it. That is the direction AGENTS.md trap 8 wants.



-- The enum vocabulary this file needs. Every value list is the
-- MySQL one, in MySQL's order, and spec/enums.yaml is the source.

