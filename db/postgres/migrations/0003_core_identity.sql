-- --------------------------------------------------------------------------
-- personal_access_tokens  (legacy table: `personal_access_tokens`)
-- Stays in MySQL with 'users' (ADR-0018). Sanctum stores sha256(token) -
-- lowercase hex - and looks it up on EVERY authenticated request. citext
-- preserves MySQL's case-insensitive matching exactly; the value is already
-- lowercase, so the behaviour difference is nil either way. It is citext
-- because "every token lookup breaks" is the single worst failure mode in
-- this migration (REWRITE-PLAN risk R2).
-- --------------------------------------------------------------------------
CREATE TABLE personal_access_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tokenable_type text NOT NULL,
    CONSTRAINT personal_access_tokens_tokenable_type_length CHECK (char_length(tokenable_type) <= 255),
    tokenable_id bigint NOT NULL,
    name text NOT NULL,
    token citext NOT NULL,
    CONSTRAINT personal_access_tokens_token_length CHECK (char_length(token) <= 64),
    abilities text,
    last_used_at timestamptz,
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT personal_access_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT personal_access_tokens_token_key UNIQUE (token)
);

CREATE INDEX personal_access_tokens_expires_at_index ON personal_access_tokens (expires_at);
CREATE INDEX personal_access_tokens_tokenable_type_tokenable_id_index ON personal_access_tokens (tokenable_type, tokenable_id);

