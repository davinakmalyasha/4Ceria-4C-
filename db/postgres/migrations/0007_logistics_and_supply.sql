-- =============================================================================
-- 0007 — Logistics and supply.
--
-- WHY THIS FILE EXISTS
-- --------------------
-- Materials, quotes, orders and the couriers who deliver them. This is the
-- second money path: a material payment is booked against the buyer's
-- project escrow through the SAME ledger as everything else, with
-- 'MaterialOrder' and 'MaterialQuote' as two of the fourteen reference
-- types in the registry (0002).
--
-- 'material_order_items.price_at_order' is the price the buyer agreed to,
-- captured at the moment the order was placed. It is deliberately NOT
-- derived from the catalogue: a later catalogue edit must not change what
-- was already agreed, which is the same rule the payment stages follow with
-- their retention split.
--
-- 'delivery_jobs.agreed_fee' is money too, and it is paid by the PLATFORM
-- rather than out of an escrow - so it is 'numeric(24,2)' like every other
-- money column, but it never appears in the ledger.



-- The enum vocabulary this file needs. Every value list is the
-- MySQL one, in MySQL's order, and spec/enums.yaml is the source.

CREATE TYPE material_orders_status AS ENUM ('pending', 'awaiting_payment', 'verifying', 'paid', 'shipping', 'delivered', 'completed', 'cancelled', 'processing', 'ready_for_pickup', 'refunded');

-- --------------------------------------------------------------------------
-- materials  (legacy table: `materials`)
-- A supplier's catalogue item.
-- --------------------------------------------------------------------------
CREATE TABLE materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    supplier_id bigint NOT NULL,
    name text NOT NULL,
    CONSTRAINT materials_name_length CHECK (char_length(name) <= 255),
    description text,
    price numeric(24,2) NOT NULL,
    unit text NOT NULL,
    CONSTRAINT materials_unit_length CHECK (char_length(unit) <= 255),
    category text NOT NULL,
    CONSTRAINT materials_category_length CHECK (char_length(category) <= 255),
    stock integer NOT NULL DEFAULT 0,
    is_available boolean NOT NULL DEFAULT true,
    image_path text,
    CONSTRAINT materials_image_path_length CHECK (char_length(image_path) <= 255),
    specifications jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT materials_pkey PRIMARY KEY (id),
    CONSTRAINT materials_supplier_id_fkey FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE CASCADE
);

CREATE INDEX materials_available_created_idx ON materials (is_available, created_at);
CREATE INDEX materials_category_price_idx ON materials (category, price);

-- --------------------------------------------------------------------------
-- material_images  (legacy table: `material_images`)
-- Images of a catalogue item.
-- --------------------------------------------------------------------------
CREATE TABLE material_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    material_id bigint NOT NULL,
    image_path text NOT NULL,
    CONSTRAINT material_images_image_path_length CHECK (char_length(image_path) <= 255),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT material_images_pkey PRIMARY KEY (id),
    CONSTRAINT material_images_material_id_fkey FOREIGN KEY (material_id) REFERENCES materials (id) ON DELETE CASCADE
);

-- --------------------------------------------------------------------------
-- material_quotes  (legacy table: `material_quotes`)
-- A buyer's quote request to a supplier.
-- --------------------------------------------------------------------------
CREATE TABLE material_quotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    supplier_id bigint NOT NULL,
    project_id bigint,
    items jsonb NOT NULL,
    delivery_address text NOT NULL,
    total_amount numeric(24,2) NOT NULL DEFAULT 0.00,
    status text NOT NULL DEFAULT 'pending',
    CONSTRAINT material_quotes_status_length CHECK (char_length(status) <= 255),
    note text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    shipping_cost numeric(24,2) NOT NULL DEFAULT 0.00,
    delivery_method text,
    CONSTRAINT material_quotes_delivery_method_length CHECK (char_length(delivery_method) <= 50),
    latitude numeric(10,7),
    longitude numeric(10,7),
    address_detail text,
    total_weight numeric(10,2),
    payment_proof_path text,
    CONSTRAINT material_quotes_payment_proof_path_length CHECK (char_length(payment_proof_path) <= 255),
    paid_at timestamptz,
    payment_verified_by bigint,
    payment_verified_at timestamptz,
    payment_notes text,
    CONSTRAINT material_quotes_pkey PRIMARY KEY (id),
    CONSTRAINT material_quotes_project_id_fkey FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE SET NULL,
    CONSTRAINT material_quotes_supplier_id_fkey FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE CASCADE,
    CONSTRAINT material_quotes_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX material_quotes_supplier_id_status_index ON material_quotes (supplier_id, status);

-- --------------------------------------------------------------------------
-- material_orders  (legacy table: `material_orders`)
-- An order placed against a quote.
-- --------------------------------------------------------------------------
CREATE TABLE material_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    supplier_id bigint NOT NULL,
    project_id bigint,
    -- The legacy column is `ENUM(...) DEFAULT 'pending'`. The default was
    -- missing here until the schema-honesty gate started comparing defaults
    -- as well as columns: an INSERT that omits the column gets 'pending' in
    -- MySQL and NULL in PostgreSQL, and the two engines then disagree about
    -- the state of an order that was never given one.
    status material_orders_status DEFAULT 'pending',
    verification_notes text,
    total_price numeric(24,2) NOT NULL,
    shipping_cost numeric(24,2) NOT NULL DEFAULT 0.00,
    whatsapp_order_id text NOT NULL,
    CONSTRAINT material_orders_whatsapp_order_id_length CHECK (char_length(whatsapp_order_id) <= 255),
    payment_proof_path text,
    CONSTRAINT material_orders_payment_proof_path_length CHECK (char_length(payment_proof_path) <= 255),
    notes text,
    paid_at timestamptz,
    shipped_at timestamptz,
    delivered_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    refunded_amount numeric(24,2) NOT NULL DEFAULT 0.00,
    delivery_method text,
    CONSTRAINT material_orders_delivery_method_length CHECK (char_length(delivery_method) <= 50),
    ready_for_pickup_at timestamptz,
    latitude numeric(10,7),
    longitude numeric(10,7),
    delivery_address text,
    address_detail text,
    delivery_documentation_path text,
    CONSTRAINT material_orders_delivery_documentation_path_length CHECK (char_length(delivery_documentation_path) <= 255),
    is_stock_decremented boolean NOT NULL DEFAULT false,
    total_weight numeric(10,2),
    CONSTRAINT material_orders_pkey PRIMARY KEY (id),
    CONSTRAINT material_orders_whatsapp_order_id_key UNIQUE (whatsapp_order_id),
    CONSTRAINT material_orders_project_id_fkey FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE SET NULL,
    CONSTRAINT material_orders_supplier_id_fkey FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE CASCADE,
    CONSTRAINT material_orders_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX material_orders_supplier_id_status_index ON material_orders (supplier_id, status);
CREATE INDEX material_orders_user_id_created_at_index ON material_orders (user_id, created_at);

-- --------------------------------------------------------------------------
-- material_order_items  (legacy table: `material_order_items`)
-- A line item of an order, priced AT THE TIME OF THE ORDER.
-- --------------------------------------------------------------------------
CREATE TABLE material_order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_id bigint NOT NULL,
    material_id bigint NOT NULL,
    quantity integer NOT NULL,
    price_at_order numeric(24,2) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    requirement_id bigint,
    CONSTRAINT material_order_items_pkey PRIMARY KEY (id),
    CONSTRAINT material_order_items_material_id_fkey FOREIGN KEY (material_id) REFERENCES materials (id) ON DELETE CASCADE,
    CONSTRAINT material_order_items_order_id_fkey FOREIGN KEY (order_id) REFERENCES material_orders (id) ON DELETE CASCADE
);

CREATE INDEX material_order_items_requirement_id_index ON material_order_items (requirement_id);

-- --------------------------------------------------------------------------
-- material_order_reviews  (legacy table: `material_order_reviews`)
-- A buyer's review of a delivered order.
-- --------------------------------------------------------------------------
CREATE TABLE material_order_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    supplier_id bigint NOT NULL,
    order_id bigint NOT NULL,
    rating integer NOT NULL DEFAULT 5,
    comment text,
    image_path text,
    CONSTRAINT material_order_reviews_image_path_length CHECK (char_length(image_path) <= 255),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    delivery_rating integer,
    delivery_comment text,
    delivery_user_id bigint,
    image_paths jsonb,
    delivery_image_paths jsonb,
    CONSTRAINT material_order_reviews_pkey PRIMARY KEY (id),
    CONSTRAINT material_order_reviews_order_id_key UNIQUE (order_id),
    CONSTRAINT material_order_reviews_order_id_fkey FOREIGN KEY (order_id) REFERENCES material_orders (id) ON DELETE CASCADE,
    CONSTRAINT material_order_reviews_supplier_id_fkey FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE CASCADE,
    CONSTRAINT material_order_reviews_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX material_order_reviews_delivery_user_id_index ON material_order_reviews (delivery_user_id);

-- --------------------------------------------------------------------------
-- delivery_jobs  (legacy table: `delivery_jobs`)
-- A courier delivery job for a material order.
-- --------------------------------------------------------------------------
CREATE TABLE delivery_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    quote_id bigint NOT NULL,
    order_id bigint,
    logistics_id bigint,
    pickup_address text,
    dropoff_address text,
    status text NOT NULL DEFAULT 'pending',
    CONSTRAINT delivery_jobs_status_length CHECK (char_length(status) <= 255),
    agreed_fee numeric(24,2),
    estimated_weight text,
    CONSTRAINT delivery_jobs_estimated_weight_length CHECK (char_length(estimated_weight) <= 255),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    pickup_photos jsonb,
    delivery_photos jsonb,
    CONSTRAINT delivery_jobs_pkey PRIMARY KEY (id),
    CONSTRAINT delivery_jobs_logistics_id_fkey FOREIGN KEY (logistics_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT delivery_jobs_order_id_fkey FOREIGN KEY (order_id) REFERENCES material_orders (id) ON DELETE CASCADE,
    CONSTRAINT delivery_jobs_quote_id_fkey FOREIGN KEY (quote_id) REFERENCES material_quotes (id) ON DELETE CASCADE
);

CREATE INDEX delivery_jobs_logistics_id_status_index ON delivery_jobs (logistics_id, status);
CREATE INDEX delivery_jobs_status_created_at_index ON delivery_jobs (status, created_at);
