-- 0024: shared rate-limit hits + mail outbox.
--
-- `rate_limit_hits` backs `PgLimiter` (fixed window per key, shared across
-- replicas — the in-memory limiter is per-process). Rows are pruned on write.
-- `mail_outbox` queues receipt/digest mails the request path must not block
-- on; the scheduler sends via Resend when `RESEND_API_KEY` is set, else logs
-- (same posture as the password mailer).

CREATE TABLE IF NOT EXISTS rate_limit_hits (
  key text NOT NULL,
  hit_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rate_limit_hits_key_at ON rate_limit_hits (key, hit_at);

CREATE TABLE IF NOT EXISTS mail_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_email text NOT NULL,
  subject text NOT NULL,
  html text NOT NULL DEFAULT '',
  text_body text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT date_trunc('second', now()),
  sent_at timestamptz,
  error text
);
CREATE INDEX IF NOT EXISTS mail_outbox_unsent ON mail_outbox (id) WHERE sent_at IS NULL;
