-- 0026: B3 weight + B4 bridge + B9 owner ratings.
--
-- B3: `project_milestones.weight` (default 1) for weighted progress %.
-- B4: `project_procurement_requests.material_order_id` linking an approved
--     request to the material order it spawned.
-- B9: `owner_ratings` — pros review owners (polymorphic target), closing the
--     one-sided review gap for structural/mep/couriers via the generic path.

ALTER TABLE project_milestones ADD COLUMN IF NOT EXISTS weight numeric(8,2) NOT NULL DEFAULT 1.00;

ALTER TABLE project_procurement_requests ADD COLUMN IF NOT EXISTS material_order_id bigint REFERENCES material_orders(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS procurement_order_idx ON project_procurement_requests (material_order_id);

CREATE TABLE IF NOT EXISTS owner_ratings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  reviewer_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reviewer_role text NOT NULL DEFAULT '',
  rating integer NOT NULL DEFAULT 5 CHECK (rating >= 1 AND rating <= 5),
  komentar text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT date_trunc('second', now()),
  updated_at timestamptz NOT NULL DEFAULT date_trunc('second', now()),
  UNIQUE (project_id, reviewer_user_id)
);
CREATE INDEX IF NOT EXISTS owner_ratings_project_idx ON owner_ratings (project_id);
