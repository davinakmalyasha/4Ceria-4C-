-- 0027_ai_chat.sql — the AI assistant's chat history.
--
-- Two tables, both user-owned: ai_chat_sessions (one row per conversation)
-- and ai_chat_messages (append-only turns). Deleting a session cascades to
-- its messages. Quotas are computed from the messages table, so no counter
-- can drift. All timestamps are timestamptz; the pool pins sessions to UTC.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE ai_chat_sessions (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    user_id bigint NOT NULL,
    title text NOT NULL DEFAULT 'New chat',
    CONSTRAINT ai_chat_sessions_title_length CHECK (char_length(title) <= 120),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_chat_sessions_pkey PRIMARY KEY (id),
    CONSTRAINT ai_chat_sessions_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ai_chat_sessions_user_updated_idx ON ai_chat_sessions (user_id, updated_at DESC);

CREATE TABLE ai_chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    session_id uuid NOT NULL,
    role text NOT NULL,
    CONSTRAINT ai_chat_messages_role_check CHECK (role IN ('user', 'assistant', 'system')),
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_chat_messages_pkey PRIMARY KEY (id),
    CONSTRAINT ai_chat_messages_session_id_fkey FOREIGN KEY (session_id) REFERENCES ai_chat_sessions (id) ON DELETE CASCADE
);

CREATE INDEX ai_chat_messages_session_idx ON ai_chat_messages (session_id, id);
CREATE INDEX ai_chat_messages_created_idx ON ai_chat_messages (created_at);
