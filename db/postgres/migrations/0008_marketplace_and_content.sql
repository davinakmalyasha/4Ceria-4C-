-- ---------------------------------------------------------------------------
-- The SEARCH family. Every one of these columns is searched with a
-- LIKE '%term%', and under MySQL that LIKE was case-insensitive. The rule for
-- the port is: lower(col) LIKE lower(?), and the index below is built on the
-- SAME expression, so the index and the query cannot drift apart.
-- ---------------------------------------------------------------------------
-- The SEARCH family: the query must be `lower(name) LIKE lower(?)`, and this
-- index is built on the same expression so the two cannot drift apart.
CREATE INDEX users_name_search_idx ON users USING gin (lower(name) gin_trgm_ops);

-- The SEARCH family: the query must be `lower(title) LIKE lower(?)`, and this
-- index is built on the same expression so the two cannot drift apart.
CREATE INDEX projects_title_search_idx ON projects USING gin (lower(title) gin_trgm_ops);

