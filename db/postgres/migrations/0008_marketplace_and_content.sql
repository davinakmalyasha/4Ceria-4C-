-- --------------------------------------------------------------------------
-- favorites  (legacy table: `favorites`)
-- A favourite. 'favoritable_type' is a polymorphic model name - the same
-- class of defect ADR-0013 retired in the ledger - but it is a display
-- concern, not a money one, and it has two live values. It is left as
-- text here and listed in docs/POSTGRES-SCHEMA.md as a deliberate
-- carry-over.
-- --------------------------------------------------------------------------
CREATE TABLE favorites (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id bigint NOT NULL,
    favoritable_type text NOT NULL,
    CONSTRAINT favorites_favoritable_type_length CHECK (char_length(favoritable_type) <= 255),
    favoritable_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT favorites_pkey PRIMARY KEY (id),
    CONSTRAINT favorites_key UNIQUE (user_id, favoritable_type, favoritable_id),
    CONSTRAINT favorites_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX favorites_user_type_index ON favorites (user_id, favoritable_type);

-- --------------------------------------------------------------------------
-- conversations  (legacy table: `conversations`)
-- A chat conversation between two users.
-- --------------------------------------------------------------------------
CREATE TABLE conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_one_id bigint NOT NULL,
    user_two_id bigint NOT NULL,
    last_message_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT conversations_pkey PRIMARY KEY (id),
    CONSTRAINT conversations_user_one_id_user_two_id_key UNIQUE (user_one_id, user_two_id),
    CONSTRAINT conversations_user_one_id_fkey FOREIGN KEY (user_one_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT conversations_user_two_id_fkey FOREIGN KEY (user_two_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX conversations_user_one_last_message_idx ON conversations (user_one_id, last_message_at);
CREATE INDEX conversations_user_two_last_message_idx ON conversations (user_two_id, last_message_at);

