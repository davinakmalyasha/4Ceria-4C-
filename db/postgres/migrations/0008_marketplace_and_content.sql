-- =============================================================================
-- 0008 — Marketplace and content.
--
-- WHY THIS FILE EXISTS
-- --------------------
-- The public marketplace (listed houses, rooms, their photos and questions),
-- the reference data it hangs off (provinces, regions), and the social
-- surfaces that are not part of the project domain (favourites, chat,
-- sticky notes).
--
-- THE SEARCH COLUMNS — THE OTHER HALF OF THE COLLATION DECISION
-- --------------------------------------------------------------
-- 'house.name', 'materials.name', 'suppliers.store_name' and the other
-- human-facing text columns are searched with a LIKE '%term%'. Under MySQL
-- that LIKE was case-insensitive AND accent-insensitive; under PostgreSQL
-- it is neither. The decision (ADR-0008):
--
--   * the QUERY must fold the case explicitly - lower(col) LIKE lower(?)
--     - and the index below is built on the same expression, so the index
--     and the query cannot drift apart;
--   * the index is a GIN TRIGRAM index, because a b-tree cannot serve an
--     infix match and every one of these searches is an infix match;
--   * ACCENT-insensitivity is NOT reproduced. MySQL's utf8mb4_0900_ai_ci
--     strips accents, so 'cafe' matched 'cafe' there. PostgreSQL's C
--     collation does not. This is a search-RECALL difference and it is
--     called out in docs/POSTGRES-SCHEMA.md; reproducing it would need the
--     unaccent extension and a functional index on unaccent(col), which is
--     a decision for the parity phase, not for the schema baseline.
--
-- 'favorites.favoritable_type' is a polymorphic model NAME and is the last
-- place in the schema where one survives. It is not money and it has two
-- live values, so it is carried over rather than replaced.



-- --------------------------------------------------------------------------
-- provinces  (legacy table: `provinces`)
-- The Indonesian province list.
-- --------------------------------------------------------------------------
CREATE TABLE provinces (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name text NOT NULL,
    CONSTRAINT provinces_name_length CHECK (char_length(name) <= 255),
    CONSTRAINT provinces_pkey PRIMARY KEY (id)
);

-- --------------------------------------------------------------------------
-- regions  (legacy table: `regions`)
-- The region (regency/city) list, under a province.
-- --------------------------------------------------------------------------
CREATE TABLE regions (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name text NOT NULL,
    CONSTRAINT regions_name_length CHECK (char_length(name) <= 255),
    id_province bigint NOT NULL,
    CONSTRAINT regions_pkey PRIMARY KEY (id),
    CONSTRAINT regions_id_province_fkey FOREIGN KEY (id_province) REFERENCES provinces (id) ON DELETE CASCADE
);

-- --------------------------------------------------------------------------
-- house  (legacy table: `house`)
-- A listed house for sale.
-- --------------------------------------------------------------------------
CREATE TABLE house (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name text NOT NULL,
    CONSTRAINT house_name_length CHECK (char_length(name) <= 255),
    price numeric(24,2),
    house_desc text,
    width text,
    CONSTRAINT house_width_length CHECK (char_length(width) <= 255),
    length text,
    CONSTRAINT house_length_length CHECK (char_length(length) <= 255),
    br integer NOT NULL DEFAULT 0,
    ba integer NOT NULL DEFAULT 0,
    floors integer NOT NULL DEFAULT 1,
    coordinate text,
    CONSTRAINT house_coordinate_length CHECK (char_length(coordinate) <= 255),
    street_name text,
    CONSTRAINT house_street_name_length CHECK (char_length(street_name) <= 255),
    kelurahan text,
    CONSTRAINT house_kelurahan_length CHECK (char_length(kelurahan) <= 255),
    kecamatan text,
    CONSTRAINT house_kecamatan_length CHECK (char_length(kecamatan) <= 255),
    kab_kota text,
    CONSTRAINT house_kab_kota_length CHECK (char_length(kab_kota) <= 255),
    province text,
    CONSTRAINT house_province_length CHECK (char_length(province) <= 255),
    postal_code text,
    CONSTRAINT house_postal_code_length CHECK (char_length(postal_code) <= 255),
    views integer NOT NULL DEFAULT 0,
    id_user bigint NOT NULL,
    is_suspended boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT house_pkey PRIMARY KEY (id),
    CONSTRAINT house_id_user_fkey FOREIGN KEY (id_user) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX house_is_suspended_created_at_index ON house (is_suspended, created_at);

