-- 0029_ai_memory.sql — long-term, user-owned memory for the Ceria assistant.
--
-- The chat transcript (0027) is the short-term record: the turns of one
-- conversation. Memory is the long-term record the assistant can search across
-- conversations: preferences, facts the user asked it to remember, and
-- earlier answers that are relevant to a new question.
--
-- Two rules shape the schema:
--
--   * Memory belongs to a USER, never to a session. Searching is always scoped
--     by user_id; a row from another account cannot be returned by a query.
--   * Deleting a conversation deletes the memories derived from it (the FK
--     cascade), because "delete this chat" must mean delete. Explicit notes
--     (`session_id IS NULL`) are not tied to a conversation and survive until
--     the user clears memory.
--
-- Search uses PostgreSQL full-text search with the `simple` configuration:
-- the product is bilingual (Indonesian/English) and a language-specific
-- stemming dictionary would quietly drop matches in the other language.
-- `content_tsv` is a generated column, so it cannot drift from `content`.

CREATE TABLE ai_memory_settings (
    user_id    bigint NOT NULL,
    enabled    boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ai_memory_settings_pkey PRIMARY KEY (user_id),
    CONSTRAINT ai_memory_settings_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE ai_memories (
    id         bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    bigint NOT NULL,
    session_id uuid,
    message_id bigint,
    kind       text NOT NULL,
    role       text NOT NULL,
    content    text NOT NULL,
    CONSTRAINT ai_memories_content_length CHECK (char_length(content) BETWEEN 1 AND 4000),
    CONSTRAINT ai_memories_kind_check CHECK (kind IN ('message', 'note')),
    CONSTRAINT ai_memories_role_check CHECK (role IN ('user', 'assistant', 'note')),
    CONSTRAINT ai_memories_kind_role_check CHECK (
        (kind = 'message' AND role IN ('user', 'assistant') AND message_id IS NOT NULL)
        OR (kind = 'note' AND role = 'note' AND message_id IS NULL)
    ),
    created_at timestamptz NOT NULL DEFAULT now(),
    content_tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, content)) STORED,
    CONSTRAINT ai_memories_pkey PRIMARY KEY (id),
    CONSTRAINT ai_memories_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ai_memories_session_id_fkey FOREIGN KEY (session_id) REFERENCES ai_chat_sessions (id) ON DELETE CASCADE,
    CONSTRAINT ai_memories_message_id_fkey FOREIGN KEY (message_id) REFERENCES ai_chat_messages (id) ON DELETE CASCADE
);

-- One memory per stored message. The partial unique index is the ingestion
-- idempotency key: a turn may be ingested more than once (retry, reconnect)
-- without duplicating its context.
CREATE UNIQUE INDEX ai_memories_message_idx
    ON ai_memories (session_id, message_id)
    WHERE message_id IS NOT NULL;

CREATE INDEX ai_memories_user_created_idx ON ai_memories (user_id, created_at DESC);
CREATE INDEX ai_memories_user_kind_idx ON ai_memories (user_id, kind, created_at DESC);
CREATE INDEX ai_memories_tsv_idx ON ai_memories USING gin (content_tsv);

COMMENT ON TABLE ai_memories IS
    'User-owned long-term assistant memory: message-derived context plus explicit notes.';
COMMENT ON COLUMN ai_memories.kind IS
    'message = derived from a chat turn; note = explicitly remembered by the user.';
