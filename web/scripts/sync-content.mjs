#!/usr/bin/env node
/**
 * sync-content.mjs — the shared code and data the port RUNS but does not own.
 *
 * WHAT IS COPIED, AND WHY COPYING IS THE RIGHT ANSWER
 * ---------------------------------------------------
 * The port has to be indistinguishable from the application it replaces. For the
 * DATA that is non-negotiable (the Help Centre's 2 000 lines of prose), and for
 * the COMPONENTS it is the difference between porting 300 of them by hand — 300
 * chances to change a screen nobody asked to change — and running the existing
 * ones on the new runtime.
 *
 * So this is PHASE 1 of the frontend port: the shell, the routing, the session
 * and the data fetching are the port's own code (`web/app`, `web/components`,
 * `web/lib`, `web/context`), and the leaf components are the legacy ones,
 * unchanged, on the new runtime. A leaf is rewritten when it needs to be, and
 * the copy shrinks.
 *
 * THE FOUR TRANSFORMS, AND NOTHING ELSE
 * -------------------------------------
 *   1. `'use client';` on every .tsx — they hold state.
 *   2. `@ts-nocheck` — the legacy tree carries type debt that its own suite
 *      tracks with a RATCHET (94 errors, may not rise). Re-typing 300 components
 *      is a different project; the port's own code has no such comment and is
 *      checked in full by `tsc --noEmit`.
 *   3. `import.meta.env.DEV` → `process.env.NODE_ENV !== 'production'` — Vite's
 *      environment object does not exist under Turbopack, and reading it throws.
 *   4. `'…/context/AuthContext'` → `'@/context/AuthContext'` — the PORT's
 *      provider, which is handed the server-resolved user instead of reading
 *      `localStorage`.
 *
 * USAGE
 *   node scripts/sync-content.mjs
 *   node scripts/sync-content.mjs --check
 */

import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import path, { resolve, dirname, isAbsolute, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(WEB, '..');
const SOURCE = join(ROOT, 'resources', 'js');
const TARGET = join(WEB, 'content');

const check = process.argv.includes('--check');

const BANNER =
    '/* GENERATED by web/scripts/sync-content.mjs — DO NOT EDIT.\n' +
    '   The source is resources/js; edit it THERE and re-run `npm run sync:content`. */\n';

/** Whole trees, copied recursively. */
const TREES = [
    'components',
    'hooks',
    'types',
    'utils',
    'constants',
    'lib',

    // The admin pages are SYNCED (the whole area is ported); the guest pages
    // are not, because they are the port's own server components.
    'pages/admin',
];

/** Individual files that live outside those trees. */
const SINGLES = [
    'context/ToastContext.tsx',
    'context/CartContext.tsx',

    // The axios wiring: the port's BFF supplies the identity, so the token
    // handling in here is inert — but the GET cache, the retry and the error
    // normalisation are the behaviour the pages were written against.
    'api.js',
];

/** Every `.ts`/`.tsx` under `dir`, relative to `sourceRoot`. */
function walk(dir, sourceRoot) {
    const found = [];

    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const absolute = join(dir, entry.name);

        if (entry.isDirectory()) {
            found.push(...walk(absolute, sourceRoot));
            continue;
        }

        if (!/\.(ts|tsx)$/.test(entry.name)) {
            continue;
        }

        // The test suite is not application code.
        if (/\.test\.(ts|tsx)$/.test(entry.name)) {
            continue;
        }

        found.push(path.relative(sourceRoot, absolute).split(path.sep).join('/'));
    }

    return found;
}

/**
 * The four transforms. Everything else is byte-for-byte the source.
 */
function transform(relative, contents) {
    let output = contents;

    // 3 and 4 come first: they are edits to the body, and the preamble is
    // prepended afterwards so a `@ts-nocheck` can never be pushed off line 1
    // (TypeScript only honours it in the leading comments).
    output = output
        .replaceAll('import.meta.env.DEV', "process.env.NODE_ENV !== 'production'")
        .replaceAll(/from '(?:\.\.\/)+context\/AuthContext'/g, "from '@/context/AuthContext'");

    const noCheck = '// @ts-nocheck — legacy tree, checked by the legacy ratchet.\n';

    if (!relative.endsWith('.tsx')) {
        return noCheck + BANNER + output;
    }

    return noCheck + "'use client';\n" + BANNER + output;
}

const files = [];

for (const tree of TREES) {
    const root = join(SOURCE, tree);

    if (!existsSync(root)) {
        throw new Error(`sync-content: ${root} is missing`);
    }

    for (const relative of walk(root, SOURCE)) {
        files.push(relative);
    }
}

for (const single of SINGLES) {
    if (!existsSync(join(SOURCE, single))) {
        throw new Error(`sync-content: ${single} is missing`);
    }

    files.push(single);
}

files.sort();

let stale = 0;

for (const relative of files) {
    const destination = join(TARGET, relative);
    const expected = transform(relative, readFileSync(join(SOURCE, relative), 'utf8'));

    if (check) {
        const current = existsSync(destination) ? readFileSync(destination, 'utf8') : '';

        if (current !== expected) {
            stale += 1;
            console.error(`::error::web/content/${relative} is stale. Run: npm run sync:content`);
        }

        continue;
    }

    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, expected, 'utf8');
}

// Files that no longer exist upstream must not linger here: a component that
// was deleted in the application but still exists in the copy is a screen the
// port renders and the product does not.
if (!check && existsSync(TARGET)) {
    const expectedPaths = new Set(files.map((relative) => join(TARGET, relative)));
    let removed = 0;

    const prune = (dir) => {
        for (const entry of readdirSync(dir, { withFileTypes: true })) {
            const absolute = join(dir, entry.name);

            if (entry.isDirectory()) {
                prune(absolute);

                if (readdirSync(absolute).length === 0) {
                    rmSync(absolute, { recursive: true, force: true });
                }

                continue;
            }

            if (!expectedPaths.has(absolute)) {
                rmSync(absolute, { force: true });
                removed += 1;
            }
        }
    };

    prune(TARGET);

    if (removed > 0) {
        console.log(`pruned ${removed} file(s) that no longer exist upstream.`);
    }
}

if (check) {
    if (stale > 0) {
        process.exit(1);
    }

    console.log(`web/content is in sync (${files.length} file(s)).`);
    process.exit(0);
}

console.log(`synced ${files.length} file(s) into web/content.`);
