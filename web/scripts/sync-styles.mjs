#!/usr/bin/env node
/**
 * sync-styles.mjs — the port shares the ORIGINAL stylesheets, byte for byte.
 *
 * WHY COPY RATHER THAN RETYPE
 * ---------------------------
 * The visual contract is pixel identity (P-2). Two hand-maintained copies of
 * 1 600 lines of CSS are two copies that diverge on the first afternoon, and
 * the divergence is invisible until a screenshot diff blames the component.
 *
 * So `web/styles/` is GENERATED from `resources/css/` — the files the legacy
 * application actually ships — and `--check` fails the build when it is stale.
 * The port cannot silently drift from the design it is meant to reproduce.
 *
 * The `@source` directives inside `app.css` are relative to the file's own
 * directory (`../../resources/js/...`). `web/styles/` sits at the same depth
 * as `resources/css/`, so those paths resolve to the same place without a
 * rewrite. That is a coincidence of layout, so it is ASSERTED below rather
 * than assumed: a moved directory fails here instead of producing a
 * stylesheet that has quietly stopped scanning the application.
 *
 * USAGE
 *   node scripts/sync-styles.mjs          # write web/styles/
 *   node scripts/sync-styles.mjs --check  # fail if stale
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(WEB, '..');
const TARGET = join(WEB, 'styles');

const check = process.argv.includes('--check');

/** The stylesheets, in the order app.tsx imports them. */
const FILES = ['app.css', 'index.css'];

/**
 * What the PORT scans for classes.
 *
 * `app.css` scans `../../resources/js/**` because the legacy markup lives
 * there. The port's markup lives in `web/app`, and Turbopack REFUSES to load a
 * file outside its configured root — so the `@source` lines are REWRITTEN
 * here rather than reused.
 *
 * The vendor and Blade sources are dropped for the same reason: there are no
 * Blade views in this application. Tailwind emits exactly the classes it finds,
 * and the port uses the same class names as the screens it replaces, so the
 * stylesheet that reaches the browser is the same one the baseline describes.
 */
const PORT_SOURCES = [
    "@source '../app/**/*.tsx';",
    "@source '../app/**/*.ts';",
    "@source '../lib/**/*.ts';",
];

/** The legacy `@source` line that anchors where the port's block is inserted. */
const LEGACY_ANCHOR = /^@source\s+'\.\.\/\.\.\/resources\/js\/\*\*\/\*\.tsx';/;

/**
 * Replace the legacy `@source` block with the port's.
 *
 * Everything else — the theme, the custom utilities, every rule — is copied
 * byte for byte. This is the ONLY transformation the sync applies, and it is
 * limited to path directives so that the declarative design cannot drift.
 */
function retargetSources(contents) {
    const lines = contents.split(String.fromCharCode(10));
    const out = [];
    let inserted = false;

    for (const line of lines) {
        if (LEGACY_ANCHOR.test(line)) {
            if (!inserted) {
                out.push(...PORT_SOURCES);
                inserted = true;
            }

            continue;
        }

        // Any other @source is a legacy-only tree (Blade, vendor pagination).
        if (/^@source\s+/.test(line)) {
            continue;
        }

        out.push(line);
    }

    if (!inserted) {
        throw new Error(
            'app.css no longer contains the legacy @source anchor; the sources for the port ' +
            'cannot be inserted blindly.',
        );
    }

    return out.join(String.fromCharCode(10));
}

const outputs = [];

for (const file of FILES) {
    const source = join(ROOT, 'resources', 'css', file);

    if (!existsSync(source)) {
        console.error(`::error::${source} is missing — the design lives there.`);
        process.exit(1);
    }

    const contents = readFileSync(source, 'utf8');

    outputs.push({
        file,
        contents: file === 'app.css' ? retargetSources(contents) : contents,
    });
}

/** The order is load-bearing: `index.css` must come after Tailwind. */
const banner =
    '/* GENERATED by web/scripts/sync-styles.mjs — DO NOT EDIT.\n' +
    '   The port ships the SAME stylesheet the legacy application ships, so the\n' +
    '   design cannot drift. Run `npm run sync:styles` after editing\n' +
    '   resources/css/. */\n';

mkdirSync(TARGET, { recursive: true });

let stale = false;

// One entry stylesheet that imports the two in the legacy order.
const entry = join(TARGET, 'globals.css');
const entryContents =
    banner +
    '\n' +
    "@import './app.css';\n" +
    "@import './index.css';\n";

for (const { file, contents } of outputs) {
    const destination = join(TARGET, file);

    if (check) {
        const current = existsSync(destination) ? readFileSync(destination, 'utf8') : '';

        if (current !== banner + contents) {
            stale = true;
            console.error(`::error::web/styles/${file} is stale. Run: npm run sync:styles`);
        }

        continue;
    }

    writeFileSync(destination, banner + contents, 'utf8');
}

if (check) {
    const current = existsSync(entry) ? readFileSync(entry, 'utf8') : '';

    if (current !== entryContents) {
        stale = true;
        console.error('::error::web/styles/globals.css is stale. Run: npm run sync:styles');
    }

    if (stale) {
        process.exit(1);
    }

    console.log('web/styles is in sync with resources/css.');
    process.exit(0);
}

writeFileSync(entry, entryContents, 'utf8');

console.log(`synced ${FILES.length} stylesheet(s) into web/styles (Tailwind first, the theme second).`);
